BASE_NODES = ("SeriesmithLoadTakeVideo", "SeriesmithSaveUpscale")
SUPIR_NODES = ("CheckpointLoaderSimple", "ModelPatchLoader", "RebatchImages", "SUPIRApply",
               "CLIPTextEncode", "VAEEncode", "KSampler", "VAEDecodeTiled", "SeriesmithFramesToBatch",
               "SeriesmithFinishUpscale")
BLUR_NODES = ("OpticalFlowLoader", "SeriesmithMotionBlur")


def not_ready(jobs: list[PostJob], object_info: dict | None) -> list[str]:
    """Why this ComfyUI can't run these posts ([] when it can)."""
    if object_info is None:
        return []
    out: list[str] = []

    def need(nodes):
        for c in nodes:
            m = f"node {c} (update ComfyUI and its node packs -- seriesmith's, h3pipe's -- and restart it)"
            if c not in object_info and m not in out:
                out.append(m)

    def file_in(node, field_, want, where, url=""):
        have = J.choices_in(object_info, node, field_)
        if have is not None and want not in have:
            m = f"{want} in models/{where}/" + (f" ({url})" if url else "")
            if m not in out:
                out.append(m)

    need(BASE_NODES)
    for job in jobs:
        e = job.enhance
        if e and e["method"] == "pixel":
            out += [m for m in U.pixel_readiness(object_info, e["pixel_model"])["missing"]
                    if m not in out]
        elif e and e["method"] == "seedvr2":
            out += [m for m in U.seedvr2_readiness(object_info, e["seedvr2_model"])["missing"]
                    if m not in out]
        elif e:
            need(SUPIR_NODES)
            file_in("ModelPatchLoader", "name", e["supir_model"], "model_patches",
                    SUPIR_URL if e["supir_model"] == SUPIR_MODEL else "")
            file_in("CheckpointLoaderSimple", "ckpt_name", e["checkpoint"], "checkpoints")
        if job.face_passes or (job.faces and job.take is None):
            for c in FACES_NODES:
                m = f"the {FACES_PACK} node pack ({FACES_PACK_URL}), for the face pass"
                if c not in object_info and m not in out:
                    out.append(m)
            need(FACES_CORE_NODES)
            file_in("UNETLoader", "unet_name", FACES_UNET, "diffusion_models")
            file_in("LoraLoaderModelOnly", "lora_name", FACES_LORA, "loras")
            file_in("CLIPLoader", "clip_name", FACES_CLIP, "text_encoders")
            file_in("VAELoader", "vae_name", FACES_VAE, "vae")
            file_in("VAELoader", "vae_name", FACES_AUDIO_VAE, "vae")
            dets = J.choices_in(object_info, "H3FaceTrackCrop", "detector")
            if dets is not None:
                job.face_detectors = face_detectors(
                    dets, J.choices_in(object_info, "H3FaceTrackCrop", "fallback_detector") or [])
                if job.face_detectors is None:
                    m = f"{FACE_DETECTOR} in models/ultralytics/bbox/ (Bingsu/adetailer), for the face pass"
                    if m not in out:
                        out.append(m)
        if job.blur > 0:
            need(BLUR_NODES)
            file_in("OpticalFlowLoader", "model_name", RAFT_FILE, "optical_flow", RAFT_URL)
    return out


def face_detectors(faces: list, bodies: list) -> tuple | None:
    """The face detector and the body fallback as this ComfyUI lists them (the pack
    lists models/ultralytics/bbox plain; Impact Subpack adds bbox\\ and segm\\ names).
    None: no face detector."""
    def pick(names, want):
        hits = [n for n in names if n.replace("\\", "/").split("/")[-1] == want]
        return min(hits, key=len) if hits else None
    face = pick(faces, FACE_DETECTOR)
    return (face, pick(bodies, BODY_DETECTOR) or "none") if face else None


