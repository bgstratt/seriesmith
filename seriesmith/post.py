def seed_of(job: PostJob) -> int:
    return int((job.take.sidecar or {}).get("seed") or 0) % (1 << 50)


def finish_of(job: PostJob) -> dict:
    e = job.enhance or {}
    return {"frequency_split": e.get("frequency_split", True), "keep_soft": e.get("keep_soft", 0.0),
            "grain": e.get("grain", 0.0), "grain_seed": seed_of(job) % (1 << 32)}


def supir_nodes(g: dict, job: PostJob, images: list) -> list:
    """SUPIR on SDXL at a low denoise, one small batch of frames at a time (it
    is an image model: RebatchImages makes the batches, every node after it runs
    once a batch, SeriesmithFramesToBatch joins them), the same seed on every batch so
    every frame starts from the same noise, then its colour and tone the
    source's (SeriesmithFinishUpscale's frequency split: only its detail is kept)."""
    e = job.enhance
    g.update({
        "pp_ckpt": {"class_type": "CheckpointLoaderSimple", "inputs": {"ckpt_name": e["checkpoint"]}},
        "pp_patch": {"class_type": "ModelPatchLoader", "inputs": {"name": e["supir_model"]}},
        "pp_split": {"class_type": "RebatchImages", "inputs": {"images": images,
                                                               "batch_size": e["batch"]}},
        "pp_supir": {"class_type": "SUPIRApply", "inputs": {
            "model": ["pp_ckpt", 0], "model_patch": ["pp_patch", 0], "vae": ["pp_ckpt", 2],
            "image": ["pp_split", 0], "strength_start": 1.0, "strength_end": 1.0,
            "restore_cfg": e["restore_cfg"], "restore_cfg_s_tmin": 0.05}},
        "pp_pos": {"class_type": "CLIPTextEncode", "inputs": {"clip": ["pp_ckpt", 1], "text": e["prompt"]}},
        "pp_neg": {"class_type": "CLIPTextEncode", "inputs": {"clip": ["pp_ckpt", 1], "text": SUPIR_NEGATIVE}},
        "pp_enc": {"class_type": "VAEEncode", "inputs": {"pixels": ["pp_split", 0], "vae": ["pp_ckpt", 2]}},
        "pp_ks": {"class_type": "KSampler", "inputs": {
            "model": ["pp_supir", 0], "positive": ["pp_pos", 0], "negative": ["pp_neg", 0],
            "latent_image": ["pp_enc", 0], "seed": seed_of(job), "steps": e["steps"],
            "cfg": e["cfg"], "sampler_name": "dpmpp_2m", "scheduler": "karras",
            "denoise": e["strength"]}},
        "pp_dec": {"class_type": "VAEDecodeTiled", "inputs": {
            "samples": ["pp_ks", 0], "vae": ["pp_ckpt", 2], "tile_size": 1024, "overlap": 64,
            "temporal_size": 64, "temporal_overlap": 8}},
        "pp_join": {"class_type": "SeriesmithFramesToBatch", "inputs": {"images": ["pp_dec", 0]}},
        "pp_finish": {"class_type": "SeriesmithFinishUpscale", "inputs": {
            "images": ["pp_join", 0], "source": images, "chunk": 8, **finish_of(job)}},
    })
    return ["pp_finish", 0]


def faces_nodes(g: dict, job: PostJob, images: list, audio: list | None) -> list:
    """One H3-FaceRefine pass per character, each on the one before's output:
    track and crop their face (by their sheet when the shot has more than one),
    H3 Ref2VA re-generates the crop from the sheet at a per-frame denoise (all of
    it on a small face, 0.35x on a 120 px one), the take's audio held in the
    joint latent (`audio`; None: no sound to hold), stitched back with a
    feathered, colour-matched edge."""
    face_det, body_det = job.face_detectors or (FACE_DETECTOR, "none")
    g.update({
        "pf_unet": {"class_type": "UNETLoader", "inputs": {"unet_name": FACES_UNET, "weight_dtype": "default"}},
        "pf_lora": {"class_type": "LoraLoaderModelOnly", "inputs": {
            "model": ["pf_unet", 0], "lora_name": FACES_LORA, "strength_model": 1.0}},
        "pf_clip": {"class_type": "CLIPLoader", "inputs": {"clip_name": FACES_CLIP, "type": "minimax",
                                                          "device": "default"}},
        "pf_vae": {"class_type": "VAELoader", "inputs": {"vae_name": FACES_VAE}},
        "pf_avae": {"class_type": "VAELoader", "inputs": {"vae_name": FACES_AUDIO_VAE}},
        "pf_sampler": {"class_type": "KSamplerSelect", "inputs": {"sampler_name": "er_sde"}},
    })
    if audio:
        g["pf_aenc"] = {"class_type": "VAEEncodeAudio", "inputs": {"audio": audio, "vae": ["pf_avae", 0]}}
    many = len(job.face_passes) > 1
    for i, p in enumerate(job.face_passes):
        k = f"pf{i}_"
        track = {
            "images": images, "detector": face_det, "confidence": 0.35, "crop_factor": 3.0,
            "canvas_width": 768, "canvas_height": 768, "canvas_mode": "auto_capped_768",
            "smooth_window": 21, "size_smooth_window": 51, "smooth_method": "gaussian",
            "size_mode": "per_frame", "identity_track": many, "identity_threshold": FACES_IDENTITY,
            "select": "largest_face", "fallback_detector": body_det, "fallback_head_frac": 0.5,
            "select_index": 0, "identity_model": "insightface", "cut_detection": "none",
            "cut_threshold": 3.0, "absent_shots": "off", "X": 0, "Y": 0, "frame_index": 0}
        g[k + "sheet"] = {"class_type": "H3LoadImageFile", "inputs": {
            "project_root": job.root, "image_file": p["sheet"]}}
        if many:
            track["identity_reference"] = [k + "sheet", 0]
        g[k + "track"] = {"class_type": "H3FaceTrackCrop", "inputs": track}
        g[k + "cond"] = {"class_type": "MiniMaxH3ReferenceToVideo", "inputs": {
            "clip": ["pf_clip", 0], "prompt": p["prompt"], "width": [k + "track", 4],
            "height": [k + "track", 5], "length": [k + "track", 6], "ref_image_size": "match",
            "vae": ["pf_vae", 0], "audio_vae": ["pf_avae", 0], "ref_images.ref_image_0": [k + "sheet", 0]}}
        g[k + "inject"] = {"class_type": "H3InjectVideoLatent", "inputs": {
            "av_latent": [k + "cond", 1], "images": [k + "track", 0], "vae": ["pf_vae", 0]}}
        latent = [k + "inject", 0]
        if audio:
            # the take's own sound in the audio stream, held clean: the lips follow it
            g[k + "split"] = {"class_type": "LTXVSeparateAVLatent", "inputs": {"av_latent": latent}}
            g[k + "join"] = {"class_type": "LTXVConcatAVLatent", "inputs": {
                "video_latent": [k + "split", 0], "audio_latent": ["pf_aenc", 0]}}
            g[k + "hold"] = {"class_type": "SeriesmithHoldAudio", "inputs": {"latent": [k + "join", 0]}}
            latent = [k + "hold", 0]
        g.update({
            k + "denoise": {"class_type": "H3PerFrameDenoise", "inputs": {
                "model": ["pf_lora", 0], "av_latent": latent, "transform": [k + "track", 1],
                "denoise_multiplier_small_face": 1.0, "denoise_multiplier_large_face": 0.35,
                "scale_mode": "absolute_px", "face_px_small": 30.0, "face_px_large": 120.0,
                "gamma": 1.0, "smooth_frames": 9}},
            k + "guider": {"class_type": "BasicGuider", "inputs": {
                "model": [k + "denoise", 2], "conditioning": [k + "cond", 0]}},
            k + "sigmas": {"class_type": "BasicScheduler", "inputs": {
                "model": [k + "denoise", 2], "scheduler": "simple", "steps": FACES_STEPS,
                "denoise": job.faces["denoise"]}},
            k + "noise": {"class_type": "RandomNoise", "inputs": {"noise_seed": (seed_of(job) + i) % (1 << 50)}},
            k + "sample": {"class_type": "SamplerCustomAdvanced", "inputs": {
                "noise": [k + "noise", 0], "guider": [k + "guider", 0], "sampler": ["pf_sampler", 0],
                "sigmas": [k + "sigmas", 0], "latent_image": [k + "denoise", 0]}},
            k + "decode": {"class_type": "VAEDecode", "inputs": {"samples": [k + "sample", 0], "vae": ["pf_vae", 0]}},
            k + "stitch": {"class_type": "H3FaceStitch", "inputs": {
                "base_images": images, "refined_crops": [k + "decode", 0], "transform": [k + "track", 1],
                "paste_region": "face_only", "mask_dilation": 24, "feather": 24, "colour_match": 1.0,
                "blend": 1.0, "undetected_frames": "fade_out", "feather_scales_with_crop": False}},
        })
        images = [k + "stitch", 0]
    return images


def post_graph(job: PostJob) -> dict:
    take, root = job.take, job.root
    # the faces' lips follow the sound the take was made against
    wav = take.paths.h3_wav if job.face_passes and os.path.isfile(take.paths.h3_wav) else ""
    g = {"pp_video": {"class_type": "H3LoadTakeVideo", "inputs": {
        "project_root": root, "video_file": rel(root, take.paths.up_mp4),
        "audio_file": rel(root, wav) if wav else ""}}}
    images = ["pp_video", 0]
    e = job.enhance
    if e and e["method"] == "pixel":
        images = U.pixel_nodes(g, "pp_model", "pp_pixels", images, e["pixel_model"], job.width,
                               job.height, "fp16", finish_of(job))
    elif e and e["method"] == "seedvr2":
        images = U.seedvr2_chain(g, images, e["seedvr2_model"], job.width, job.height,
                                 seed_of(job), finish_of(job), prefix="pp_sv_",
                                 chunk=e.get("chunk", 0), overlap=e.get("overlap", 2))
    elif e:
        images = supir_nodes(g, job, images)
    if job.face_passes:
        images = faces_nodes(g, job, images, ["pp_video", 1] if wav else None)
    if job.blur > 0:
        g["pp_flow"] = {"class_type": "OpticalFlowLoader", "inputs": {"model_name": RAFT_FILE}}
        g["pp_blur"] = {"class_type": "SeriesmithMotionBlur", "inputs": {
            "images": images, "optical_flow": ["pp_flow", 0], "amount": job.blur,
            "samples": 9, "flow_width": 960, "max_motion": 0.08, "chunk": 8,
            "min_motion": 0.75}}
        images = ["pp_blur", 0]
    g["pp_save"] = {"class_type": "H3SaveUpscale", "inputs": {
        "images": images, "project_root": root,
        "source_mp4": rel(root, take.paths.up_mp4), "out_mp4": rel(root, take.paths.post_mp4),
        "fps": job.fps, "sidecar": rel(root, take.paths.post_sidecar), "encoder": job.encoder,
        # the upscale it's made from is stamped as it's saved: it may be queued
        # behind that upscale, which isn't there yet
        "stamp_source": True, "event": "seriesmith.post",
        **({"quality": job.quality} if job.quality != "review" else {})}}
    return g


