def resolve_enhance(enhance) -> dict | None:
    """A tier name, a method name, a dict (`tier` or `method` plus fields) or
    None / "none": the enhance step with every field filled in, or None."""
    if enhance is None or enhance in NONE or enhance == {}:
        return None
    if isinstance(enhance, str):
        enhance = {"tier": enhance} if enhance in TIERS else {"method": enhance}
    if not isinstance(enhance, dict):
        raise PostError(f"enhance {enhance!r}: a tier ({', '.join(TIERS)}), a method "
                        f"({', '.join(METHODS)}) or an object")
    e = dict(enhance)
    tier = e.pop("tier", None)
    if tier is not None:
        if tier not in TIERS:
            raise PostError(f"enhance tier {tier!r}: it's {', '.join(TIERS)}")
        e = {**TIERS[tier], **e}
    bad = sorted(set(e) - set(ENHANCE_FIELDS) - {"_note"})
    if bad:
        raise PostError(f"enhance: not a field: {', '.join(bad)}")
    m = e.get("method")
    if m not in METHODS:
        raise PostError(f"enhance method {m!r}: it's {', '.join(METHODS)}")
    out = {"method": m, "frequency_split": bool(e.get("frequency_split", True)),
           "keep_soft": float(e.get("keep_soft", 0.0)), "grain": float(e.get("grain", 0.0))}
    if tier:
        out["tier"] = tier
    if m == "pixel":
        out["pixel_model"] = e.get("pixel_model") or U.DEFAULT_PIXEL_MODEL
    elif m == "seedvr2":
        out["seedvr2_model"] = U.seedvr2_file(e.get("seedvr2_model"))
        # fixed chunks: auto sizes them to the free VRAM, so a redo can split the
        # shot elsewhere and a face shift at different frames
        chunk, overlap = e.get("chunk", 0), e.get("overlap", 2)
        if chunk != "fit":
            chunk = int(chunk)
            if chunk and (chunk < 5 or (chunk - 1) % 4):
                raise PostError(f"SeedVR2 chunk {chunk}: 0 (auto), \"fit\" or a 4n+1 frame "
                                f"count (41, 49, 61...)")
        if overlap != "fit":
            try:
                overlap = int(overlap)
            except (TypeError, ValueError):
                overlap = -1
            if not 0 <= overlap <= 16:
                raise PostError(f"SeedVR2 overlap {overlap}: \"fit\" or 0 to 16 latent frames")
        if chunk:
            out["chunk"] = chunk
        if overlap != 2:
            out["overlap"] = overlap
    else:
        s = float(e.get("strength", 0.2))
        if not STRENGTH[0] <= s <= STRENGTH[1]:
            raise PostError(f"SUPIR strength {s:g}: {STRENGTH[0]:g} to {STRENGTH[1]:g} "
                            f"(a clean-up, not a redraw)")
        out.update(strength=s, supir_model=e.get("supir_model") or SUPIR_MODEL,
                   checkpoint=e.get("checkpoint") or SUPIR_CHECKPOINT,
                   steps=int(e.get("steps", SUPIR_STEPS)), cfg=float(e.get("cfg", SUPIR_CFG)),
                   prompt=e.get("prompt") or SUPIR_PROMPT,
                   batch=max(1, int(e.get("batch", SUPIR_BATCH))),
                   # SUPIR's pull toward the input; 0 skips its extra VAE round trip
                   restore_cfg=float(e.get("restore_cfg", 4.0)))
    return out


def check_blur(v) -> float:
    if isinstance(v, bool) or not isinstance(v, (int, float)) or not BLUR[0] <= v <= BLUR[1]:
        raise PostError(f"motion_blur {v!r}: {BLUR[0]:g} to {BLUR[1]:g} of the frame interval "
                        f"(0.5 is a 180-degree shutter)")
    return float(v)


def resolve_faces(faces) -> dict | None:
    """True / "on", an object (`denoise`, `subjects`), or None / False / "none":
    the face step with every field filled in, or None."""
    if faces is None or faces is False or faces in NONE or faces == {}:
        return None
    if faces is True or faces == "on":
        faces = {}
    if not isinstance(faces, dict):
        raise PostError(f"faces {faces!r}: true, false or an object (denoise, subjects)")
    bad = sorted(set(faces) - set(FACES_FIELDS) - {"_note"})
    if bad:
        raise PostError(f"faces: not a field: {', '.join(bad)}")
    d = faces.get("denoise", FACES_DEFAULT["denoise"])
    if isinstance(d, bool) or not isinstance(d, (int, float)) or not FACES_DENOISE[0] <= d <= FACES_DENOISE[1]:
        raise PostError(f"faces denoise {d!r}: {FACES_DENOISE[0]:g} to {FACES_DENOISE[1]:g} (H3's "
                        f"shifted schedule: 0.4 redraws a small face, more moves the head)")
    out: dict = {"denoise": float(d)}
    subs = faces.get("subjects")
    if subs is not None:
        if not isinstance(subs, list) or not all(isinstance(s, str) and s for s in subs):
            raise PostError("faces subjects: a list of subject ids (the shot's characters by default)")
        out["subjects"] = list(subs)
    return out


def _prompt_parts(prompt) -> dict:
    """The H3 Ref2VA prompt's sections by name (subject_definitions, summary,
    detailed_description...), from the list the compile made or one string."""
    text = "\n".join(prompt) if isinstance(prompt, list) else str(prompt or "")
    parts, name = {}, None
    for line in text.split("\n"):
        m = re.match(r"([a-z_]+):\s*(.*)$", line)
        if m and m.group(1) in ("subject_definitions", "summary", "retention_analysis",
                                "detailed_description", "overall_soundscape", "non_diegetic_music"):
            name = m.group(1)
            parts[name] = [m.group(2)] if m.group(2) else []
        elif name:
            parts[name].append(line)
    return {k: "\n".join(v).strip() for k, v in parts.items()}


def face_prompt(name: str, styling: str, style: str, action: str) -> str:
    """The prompt for one character's face crop: the shot's own wording (their
    definition, the look, what they do), told as a close-up of that one face."""
    look = f" Preserve the exact reference styling: {styling}." if styling else ""
    return ("subject_definitions:\n"
            f"<Subject 1> is {name}, defined by <Picture 1> — a single reference image of ONE "
            f"character. Exactly one person appears in that image.{look}\n"
            "Exactly one character appears in this shot: <Subject 1>.\n\n"
            "retention_analysis:\n<Subject 1> (appears in [Shot 1]): fully_preserved - facial identity, "
            "hairstyle and colors are retained from <Picture 1> while allowing natural expressions.\n\n"
            "detailed_description:\n" + (style + "\n" if style else "")
            + "[Shot 1] A close-up of <Subject 1>'s face and shoulders against the softly blurred "
            "background" + (f", as in this moment: {action}" if action else "") + ". The face is sharp, "
            "natural and expressive, with clear eyes and a natural mouth.")


def face_passes(root: str, take: T.Take, subjects: list | None = None) -> tuple[list, list]:
    """One pass per character in the take's shot (or `subjects`), from its frozen
    shotlist: [{subject, name, sheet (episode-relative), prompt}], and notes on
    who was left out (no sheet, not a character, not in the shot)."""
    try:
        doc = T.read_json(take.paths.shotlist)
        shot = doc["shots"][0]
    except Exception:
        return [], ["the take has no shotlist to read its characters from"]
    defs = doc.get("subjects") or {}
    in_shot = [s for s in (shot.get("subjects") or [])]
    parts = _prompt_parts(shot.get("prompt"))
    named = {}
    for m in re.finditer(r"<Subject (\d+)> is ([^,\n]+), defined by <Picture \d+>[^\n]*?"
                         r"(?:styling: ([^\n]*?))?\.?\s*$", parts.get("subject_definitions", ""), re.M):
        named[int(m.group(1))] = (m.group(2).strip(), (m.group(3) or "").strip())
    style = parts.get("detailed_description", "").split("[Shot")[0].strip()
    action = re.sub(r"^\[[^\]]*\]\s*", "", parts.get("summary", "")).strip().rstrip(".")
    want = subjects if subjects is not None else in_shot
    out, notes = [], []
    for sid in want:
        d = defs.get(sid) or {}
        if sid not in in_shot:
            notes.append(f"{sid} isn't in the shot")
            continue
        if d.get("kind", "character") != "character":
            continue
        sheet = d.get("sheet")
        if not sheet or not os.path.isfile(os.path.join(root, sheet)):
            notes.append(f"{sid} has no sheet to draw their face from")
            continue
        name, styling = named.get(in_shot.index(sid) + 1, (sid.replace("_", " ").title(), ""))
        out.append({"subject": sid, "name": name, "sheet": sheet,
                    "prompt": face_prompt(name, styling, style, action)})
    return out, notes


def face_marks(root: str, pass_: str) -> set[str]:
    """The shots of a pass's cut marked for the face pass (cut.json `refine_faces`,
    the editor's R key)."""
    try:
        return {e["shot"] for e in T.load_cut(root).get(pass_) or []
                if isinstance(e, dict) and e.get("refine_faces") and e.get("shot")}
    except Exception:                                     # noqa: BLE001  an unreadable cut: no marks
        return set()


def faces_of(root: str, pass_: str, shot: str, marks: set | None = None,
             recipe: dict | None = None, shots: dict | None = None) -> tuple:
    """The face pass a shot gets when a post isn't told either way, and why:
    (resolve_faces' input, "...") or (None, ""). The shot's own post.faces
    (overrides.json) over the series' post.master.faces ("every shot") over the
    cut's mark (R). `false` at either level turns it off, marks or not."""
    own = ((shot_recipes(root) if shots is None else shots).get(shot) or {}).get("faces")
    series = ((master_recipe(root) if recipe is None else recipe) or {}).get("faces")
    for v, why in ((own, "its own post.faces"), (series, "every shot (series settings)")):
        if v is not None:
            try:
                return (v, why) if resolve_faces(v) else (None, "")
            except PostError:
                return v, why                                 # plan_post says what's wrong
    if shot in (face_marks(root, pass_) if marks is None else marks):
        return True, "marked for faces in the cut"
    return None, ""


def settings_of(job: PostJob) -> dict:
    """What decides the post's picture (the record's `recipe`)."""
    d: dict = {"size": [job.width, job.height]}
    if job.enhance:
        d["enhance"] = {k: v for k, v in job.enhance.items() if k != "tier"}
    if job.faces and job.face_passes:
        d["faces"] = {"denoise": job.faces["denoise"],
                      "subjects": [p["subject"] for p in job.face_passes]}
    if job.blur > 0:
        d["motion_blur"] = job.blur
    if job.quality != "review":
        d["quality"] = job.quality
    return d


