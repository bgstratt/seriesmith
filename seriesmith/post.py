class PostError(ValueError):
    pass


@dataclass
class PostJob:
    root: str
    take: T.Take
    enhance: dict | None                 # resolved: {"method": ..., every field}
    blur: float
    faces: dict | None = None            # resolved: {"denoise": ..., "subjects": [...] or absent}
    face_passes: list = field(default_factory=list)  # one per character: face_passes()
    face_detectors: tuple | None = None  # (face, body) as this ComfyUI names them: not_ready
    width: int = 0
    height: int = 0
    fps: float = 24.0
    action: str = "post"                 # post | skip | error
    why: str = ""
    encoder: str = "auto"
    quality: str = "review"
    notes: list = field(default_factory=list)

    @property
    def shot(self) -> str:
        return self.take.shot

    @property
    def label(self) -> str:
        return f"{self.shot} t{self.take.take:02d}"


