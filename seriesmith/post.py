#!/usr/bin/env python3
"""
post.py — the post pass: an upscale, finished (docs/POST_PROCESSING.md).

A post is a version of the upscale, the way an upscale is a version of its
take: <stem>.post.mp4 beside it, with <stem>.post.json. It is made from the
take's fresh .up.mp4, at the same size and frame count, its audio the
upscale's own stream copied on, and it is stale when that upscale changes.

    seriesmith post <episode> [--proxy] [--only sh760,sh770] [--take N] [--redo]
                      [--enhance TIER|METHOD] [--strength 0.2] [--blur 0.25]
                      [--recipe] [--check]

Three steps, in order, each optional:

- enhance (the whole frame): `pixel` (an upscale model run at 1x, its colour
  and tone the source's: a sharpen), `seedvr2` (3b or 7b at the same size: a
  video restoration) or `supir` (SUPIR on SDXL, a low denoise, one small batch
  of frames at a time, its colour and tone the source's). The tiers are names
  for these: draft (pixel), production (SeedVR2 7B, fixed chunks sized to the
  frame, crossfaded over 6 latent frames at 1080p, 3 at 1440p, 2 at 4K),
  cinematic (SUPIR 0.2).
- faces (`--faces`): each character's face, tracked, cropped to fill a canvas,
  re-generated by H3 Ref2VA from their sheet at a low denoise (more on a small
  face, less on a large one) with the take's audio held so the lips follow it,
  and stitched back (Carasibana's ComfyUI-H3-FaceRefine). One pass a character.
- motion blur: shutter blur along each pixel's optical flow (SeriesmithMotionBlur),
  `--blur` the fraction of the frame interval (0.5: a 180-degree shutter).

Without --enhance / --faces / --blur (or with --recipe): the series config's
`post.master` recipe, each shot's own over it (overrides.json's "post").

Stdlib only.
"""
