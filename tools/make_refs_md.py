#!/usr/bin/env python3
"""
make_refs_md.py — regenerate the tables of what each model takes in pictures,
from the targets: the video models' in AUTHORING.md, the picture models' in
FULL_SETUP.md.

Every target already says how many reference pictures it takes and how
(`capabilities`, `recipe`, a hosted model's `router.inputs`, read into one form
by seriesmith.limits), how a hosted one is told which picture is whom (its
references' `define` or `mention`), and whether its provider's content filter
reads the request (Target.moderated). This writes the video table under
AUTHORING.md's "Rendering a shot on a hosted model" (what a script writer
chooses between) and the picture table under FULL_SETUP.md's "Pictures" (what
the script-writing skill, made from AUTHORING.md, doesn't need), so neither page
can drift from what the code sends.

    python tools/make_refs_md.py            # rewrite both blocks
    python tools/make_refs_md.py --check    # exit 1 if either is out of date
    python tools/make_refs_md.py --stdout   # print them, write nothing

Each block lives between its markers below; tests/test_docs.py runs --check.
Run it after changing any target's pictures, limits or how it names them.

Stdlib only.
"""
from __future__ import annotations

import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
# the shipped targets only: not the models this machine saved for every show
os.environ["SERIESMITH_SETTINGS"] = os.path.join(ROOT, "tools", "_no_settings.json")

from seriesmith import limits as L                                # noqa: E402
from seriesmith import targets as TG                              # noqa: E402

AUTHORING = os.path.join(ROOT, "docs", "AUTHORING.md")
FULL_SETUP = os.path.join(ROOT, "docs", "FULL_SETUP.md")
BEGIN = "<!-- BEGIN PICTURES (generated by tools/make_refs_md.py — do not edit) -->"
END = "<!-- END PICTURES -->"
BEGIN_IMAGE = "<!-- BEGIN PICTURE MODELS (generated by tools/make_refs_md.py — do not edit) -->"
END_IMAGE = "<!-- END PICTURE MODELS -->"

SENT = {"seedance": "through the Seedance library (`asset://`)", "base64": "inline",
        "datauri": "inline", "": "as links"}


def _refs(t) -> dict:
    router = t.spec.get("router")
    return ((router.get("inputs") or {}).get("references") or {}) if isinstance(router, dict) else {}


def _frames(caps: dict) -> str:
    ends = caps.get("keyframes") or []
    return " and ".join(ends) if ends else "—"


def video_row(t) -> str:
    caps, r, refs = t.capabilities(), t.recipe, _refs(t)
    if t.moderated:
        pics = L.describe(t.spec)["pictures"]
        n = pics.get("references") or 0
        takes = (f"up to {n}: the subjects, then the plate; {SENT.get(pics.get('via', ''), 'as links')}"
                 if n else "none")
        who = ("defines each first: *Define … in @Image N as …*" if refs.get("define")
               else f"names each: `{refs['mention'].replace('{n}', 'N')}` is …" if refs.get("mention")
               else "by their order" if n else "—")
        where = "Comfy Router"
    else:
        slots = len(r.get("subject_slots") or [])
        if slots:
            takes, who = f"{slots} subjects + the plate", "`<Subject N>` … `<Picture N>`"
        elif r.get("reference_image"):
            takes, who = "one picture made from the subjects' sheets", "by their order"
        elif r.get("ic_lora") and r.get("reference_sheet"):
            takes, who = "one sheet tiled from the subjects and the plate", "by their order"
        elif (r.get("references") or {}).get("slots"):
            # MSR's guide: a sheet a subject, then the place (`Image N`, numbered over those sent)
            n = len(r["references"]["slots"])
            takes = f"{n} subjects + the plate" if r["references"].get("background_slot") else f"{n} subjects"
            who = "`Image N`, by their order"
        else:
            takes, who = "none", "—"
        # seriesmith's own hold runs nothing of ComfyUI's: ffmpeg on this machine
        where = "this machine" if t.spec.get("local_render") else "your ComfyUI"
    frames = _frames(caps)
    if r.get("keyframes_when_asked") and frames != "—":
        frames += ", when the shot asks"                  # an H3 reference model's
    return f"| `{t.id}` | {t.short or t.label} | {where} | {takes} | {frames} | {who} |"


def image_row(t) -> str:
    caps = t.capabilities()
    pics = L.describe_image(t.spec)["pictures"]
    n = pics.get("references") or caps.get("max_refs") or 0
    mode = "edits and new pictures" if caps.get("mode") == "edit" else "new pictures"
    takes = f"up to {n}" if n else "none"
    if t.moderated and n:
        takes += f", {SENT.get(pics.get('via', ''), 'as links')}"
    where = "Comfy Router" if t.moderated else "your ComfyUI"
    return f"| `{t.id}` | {t.short or t.label} | {where} | {takes} | {mode} |"


def _targets(kind: str) -> list:
    return sorted((t for t in TG.list_targets() if t.kind == kind and not getattr(t, "custom", False)),
                  key=lambda t: (t.moderated, t.id))


def block() -> str:
    """AUTHORING.md's: the video models."""
    lines = [BEGIN, "",
             "| Video model | | Runs on | Reference pictures | Keyframes | Told who's who |",
             "|---|---|---|---|---|---|"]
    lines += [video_row(t) for t in _targets("video")]
    lines += ["", END]
    return "\n".join(lines)


def image_block() -> str:
    """FULL_SETUP.md's: the picture models."""
    lines = [BEGIN_IMAGE, "",
             "| Picture model | | Runs on | Reference pictures | Makes |",
             "|---|---|---|---|---|"]
    lines += [image_row(t) for t in _targets("image")]
    lines += ["", END_IMAGE]
    return "\n".join(lines)


BLOCKS = [(AUTHORING, BEGIN, END, block), (FULL_SETUP, BEGIN_IMAGE, END_IMAGE, image_block)]


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--stdout", action="store_true")
    args = ap.parse_args(argv)
    if args.stdout:
        print("\n\n".join(make() for _, _, _, make in BLOCKS))
        return 0
    stale = []
    for path, begin, end, make in BLOCKS:
        new = make()
        with open(path, encoding="utf-8") as fh:
            text = fh.read()
        name = os.path.relpath(path, ROOT).replace(os.sep, "/")
        if begin not in text or end not in text:
            print(f"{name}: no {begin} ... {end} block", file=sys.stderr)
            return 1
        i, j = text.index(begin), text.index(end) + len(end)
        if text[i:j] == new:
            continue
        if args.check:
            stale.append(name)
            continue
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text[:i] + new + text[j:])
        print(f"wrote {name}'s pictures table")
    if stale:
        print(f"{', '.join(stale)}: the pictures table is out of date: python tools/make_refs_md.py",
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
