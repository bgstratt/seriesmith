#!/usr/bin/env python3
"""
make_refs_md.py — regenerate AUTHORING.md's table of what each model takes in
pictures, from the targets.

Every target already says how many reference pictures it takes and how
(`capabilities`, `recipe`, a hosted model's `router.inputs`, read into one form
by seriesmith.limits), how a hosted one is told which picture is whom (its
references' `define` or `mention`), and whether its provider's content filter
reads the request (Target.moderated). This writes the two Markdown tables
(video, pictures) under "Rendering a shot on a hosted model", so the page can't
drift from what the code sends.

    python tools/make_refs_md.py            # rewrite the block in docs/AUTHORING.md
    python tools/make_refs_md.py --check    # exit 1 if it is out of date
    python tools/make_refs_md.py --stdout   # print the block, write nothing

The block lives between the markers below; tests/test_docs.py runs --check.
Run it after changing any target's pictures, limits or how it names them.

Stdlib only.
"""
from __future__ import annotations

import argparse
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
# the shipped targets only: not the models this machine saved for every show
os.environ["SERIESMITH_SETTINGS"] = os.path.join(ROOT, "tools", "_no_settings.json")

from seriesmith import limits as L                                # noqa: E402
from seriesmith import targets as TG                              # noqa: E402

AUTHORING = os.path.join(ROOT, "docs", "AUTHORING.md")
BEGIN = "<!-- BEGIN PICTURES (generated by tools/make_refs_md.py — do not edit) -->"
END = "<!-- END PICTURES -->"

SENT = {"seedance": "through the Seedance library (`asset://`)", "base64": "inline",
        "datauri": "inline", "": "as links"}


def _refs(t) -> dict:
    router = t.spec.get("router")
    return ((router.get("inputs") or {}).get("references") or {}) if isinstance(router, dict) else {}


def _frames(caps: dict) -> str:
    ends = caps.get("keyframes") or []
    return " and ".join(ends) if ends else "—"


def video_row(t) -> str:
    caps, r, refs = t.capabilities(), t.recipe, _refs(t)
    if t.moderated:
        pics = L.describe(t.spec)["pictures"]
        n = pics.get("references") or 0
        takes = (f"up to {n}: the subjects, then the plate; {SENT.get(pics.get('via', ''), 'as links')}"
                 if n else "none")
        who = ("defines each first: *Define … in @Image N as …*" if refs.get("define")
               else f"names each: `{refs['mention'].replace('{n}', 'N')}` is …" if refs.get("mention")
               else "by their order" if n else "—")
        where = "Comfy Router"
    else:
        slots = len(r.get("subject_slots") or [])
        if slots:
            takes, who = f"{slots} subjects + the plate", "`<Subject N>` … `<Picture N>`"
        elif r.get("reference_image"):
            takes, who = "one picture made from the subjects' sheets", "by their order"
        elif r.get("ic_lora") and r.get("reference_sheet"):
            takes, who = "one sheet tiled from the subjects and the plate", "by their order"
        elif (r.get("references") or {}).get("slots"):
            # MSR's guide: a sheet a subject, then the place (`Image N`, numbered over those sent)
            n = len(r["references"]["slots"])
            takes = f"{n} subjects + the plate" if r["references"].get("background_slot") else f"{n} subjects"
            who = "`Image N`, by their order"
        else:
            takes, who = "none", "—"
        where = "your ComfyUI"
    return f"| `{t.id}` | {t.short or t.label} | {where} | {takes} | {_frames(caps)} | {who} |"


def image_row(t) -> str:
    caps = t.capabilities()
    pics = L.describe_image(t.spec)["pictures"]
    n = pics.get("references") or caps.get("max_refs") or 0
    mode = "edits and new pictures" if caps.get("mode") == "edit" else "new pictures"
    takes = f"up to {n}" if n else "none"
    if t.moderated and n:
        takes += f", {SENT.get(pics.get('via', ''), 'as links')}"
    where = "Comfy Router" if t.moderated else "your ComfyUI"
    return f"| `{t.id}` | {t.short or t.label} | {where} | {takes} | {mode} |"


def block() -> str:
    targets = [t for t in TG.list_targets() if not getattr(t, "custom", False)]
    video = sorted((t for t in targets if t.kind == "video"), key=lambda t: (t.moderated, t.id))
    image = sorted((t for t in targets if t.kind == "image"), key=lambda t: (t.moderated, t.id))
    lines = [BEGIN, "",
             "| Video model | | Runs on | Reference pictures | Keyframes | Told who's who |",
             "|---|---|---|---|---|---|"]
    lines += [video_row(t) for t in video]
    lines += ["",
              "| Picture model | | Runs on | Reference pictures | Makes |",
              "|---|---|---|---|---|"]
    lines += [image_row(t) for t in image]
    lines += ["", END]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--stdout", action="store_true")
    args = ap.parse_args(argv)
    new = block()
    if args.stdout:
        print(new)
        return 0
    with open(AUTHORING, encoding="utf-8") as fh:
        text = fh.read()
    if BEGIN not in text or END not in text:
        print(f"{AUTHORING}: no {BEGIN} ... {END} block", file=sys.stderr)
        return 1
    i, j = text.index(BEGIN), text.index(END) + len(END)
    if text[i:j] == new:
        return 0
    if args.check:
        print("docs/AUTHORING.md's pictures table is out of date: python tools/make_refs_md.py",
              file=sys.stderr)
        return 1
    with open(AUTHORING, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text[:i] + new + text[j:])
    print("wrote docs/AUTHORING.md's pictures table")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
